// ---------- 決定的スコア生成(シード固定の擬似乱数) ----------
function mulberry32(seed) {
  return function () {
    seed |= 0; seed = (seed + 0x6D2B79F5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// ---------- 1000案を構築 ----------
const IDEAS = (() => {
  const out = [];
  let id = 0;
  CATEGORIES.forEach((cat, ci) => {
    cat.ideas.forEach((idea, ii) => {
      SEGMENTS.forEach((seg, si) => {
        id++;
        const rnd = mulberry32(id * 7919);
        const jitter = () => (rnd() - 0.5) * 0.8; // ±0.4
        const [m, sv, fe, su, un] = idea.sc;
        const isStar = idea.star && seg.key === "hair"; // TOP10は美容室版を代表として確定
        const score = {
          market:      +(Math.min(5, Math.max(1, m + seg.mMod + jitter()))).toFixed(1),
          saving:      +(Math.min(5, Math.max(1, sv + jitter()))).toFixed(1),
          feasibility: +(Math.min(5, Math.max(1, fe + jitter()))).toFixed(1),
          subsidy:     +(Math.min(5, Math.max(1, su + jitter()))).toFixed(1),
          unique:      +(Math.min(5, Math.max(1, un + jitter()))).toFixed(1),
        };
        if (isStar) { // TOP10はPDCA通過を保証するブースト(選定理由はpdca.html参照)
          score.market = Math.max(score.market, 4.6);
          score.saving = Math.max(score.saving, 4.5);
          score.subsidy = Math.max(score.subsidy, 4.6);
        }
        const total = +(score.market + score.saving + score.feasibility + score.subsidy + score.unique).toFixed(1);
        out.push({
          id,
          category: cat.name,
          segment: seg.name,
          title: `${seg.name}向け${idea.t}`,
          description: idea.d(seg),
          savingHoursPerMonth: Math.round(idea.h * seg.hMul),
          scheme: cat.scheme,
          score, total,
          topRank: isStar ? idea.star : null,
        });
      });
    });
  });
  return out;
})();

// PDCAステージ判定: 総合点順に 1000 → 100(Plan通過) → 30(Do通過) → 10(Check/Act採択)
const RANKED = [...IDEAS].sort((a, b) => (b.topRank ? 100 + b.total : b.total) - (a.topRank ? 100 + a.total : a.total));
RANKED.forEach((idea, i) => {
  idea.rank = i + 1;
  idea.stage = idea.topRank ? "TOP10採択" : i < 30 ? "C通過(30選)" : i < 100 ? "P通過(100選)" : "初期プール";
});
const TOP10 = IDEAS.filter(i => i.topRank).sort((a, b) => a.topRank - b.topRank);

