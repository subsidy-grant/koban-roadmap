//
// 作り方：
//   金額・率・区分は暗記で書かない。必ず一次資料（制度所管省庁のご案内・交付要綱、
//   補助金なら当該公募回の公募要領）を開いて数値を拾い、source に出典URLと
//   確認日時を入れる。拾った内容は専門家レビュー（厚生労働省系 → sharoushi、
//   経済産業省・農林水産省・観光庁・国土交通省系 → shindanshi）に通し、review に記録を残す。
//
//   ご案内・リーフレットは要約なので、それだけで書かない。2026-08-05の監修で、
//   ご案内には「令和8年度地域別最低賃金未満であること」としか書かれていない要件が、
//   交付要綱では「令和7年度地域別最低賃金以上 かつ 令和8年度未満」という帯だと分かった。
//   ご案内だけを読んで噛み砕くと、要件の意味が反転する。要綱・要領・Q&Aまで見ること。
//
// 直すときの約束：
//   ・数値を変えたら source.checked を取り直した日時に更新し、review をやり直す
//   ・「申請すればもらえる」と読める書き方にしない。kind（hojo＝補助金／josei＝助成金）は
//     必ず入れる（結果の見出しと共通の注意書きが自動で変わる）
//   ・新しい計算タイプを増やす前に、既にある型で書けないか検討する。型が増えるほど
//     制度を1つ足すコストが上がる（地域限定の97制度をこのあと足すので、ここは特に守る）
//   ・迷ったら少なめに見積もる側へ倒す。ただし「判定できるのに諦める」のは別問題で、
//     入力から機械的に判定できる要件は when で判定する（特例事業者の賃金要件がその例）
//
// 制度を1つ足す手順：
//   1. その制度の要綱・公募要領を開く（暗記で書かない）
//   2. type を選ぶ（多くは expense_rate。上限額と補助率だけで決まるため）
//   3. エントリを書く（program.html 側のコードは触らない）
//   4. python _tools/check_sim_data.py で機械チェック
//   5. Playwright で program.html?key=<制度キー> を開き、実際に数字を入れて確かめる
//   6. 専門家レビュー → review に記録
//
// 計算タイプ（program.html の計算エンジンが解釈する語彙。ここにない語は動かない）：
//   expense_rate … min（経費 × 補助率、上限額）。補助率は固定値かしきい値、
//                  上限額は固定値か区分表（軸は最大3つ）。下限額は floor で書く
//   per_person   … 単価 × 人数（上限あり）＋ 加算   ※未実装（キャリアアップ助成金等で追加予定）
//   checkbox_sum … 選んだ取組ごとの定額を合算       ※未実装（両立支援等助成金で追加予定）
//   multi_part   … 上の組み合わせを合算             ※未実装（人材開発支援助成金で追加予定）
//   none         … 金額の試算になじまない制度（reason に理由を書いて公式サイトへ誘導する）
//
// 質問の型：number（数値入力）／ choice（プルダウン）／ checkbox（複数選択）の3つだけ
//
// 注意書きは2段に分ける：
//   notes     … 金額と可否に直結するもの。常に表示する。多くても4〜5個まで
//   notesMore … そのほかの条件。既定は閉じた開閉式にする（全部並べると誰も読まない）
//
// 定義が無い制度は、program.html 側が自動で「準備中」の案内（上限額・補助率の文章を再掲）を
// 出す。だから未対応の制度があっても画面は壊れない。

