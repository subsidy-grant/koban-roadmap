//   そこで、これらは top に置き、index.html は起動時にここから読む形にした。
//   index.html 側に同じ制度の CAP / CAP_TEXT / RATE_BASE / PROGRAM_TRACKS を
//   書き残すと _tools/check_sim_data.py が落ちる。
//
//   top: {
//     rate, cap, schedule … 一覧と制度詳細ページに出す説明文（PROGRAMS[key] の同名項目になる）
//     capKey              … 概算に使う上限額。数字は書かず calc.cap.values のキーで指す
//                           （書き写すと必ず片方が古くなる。fixedMan の制度は省略）
//     capText             … 上限額の表示。capKey が指す額を必ず含めること（機械チェックあり）
//     tracks              … 枠・コースの選択肢。上限は capKey / capKeyByTier で指す。
//                           calc に無い枠（AI導入のインボイス枠など）だけ capMan に直書きし、
//                           なぜ calc に無いのかをコメントで残す
//     noTopEstimate       … true なら概算の対象から外す（金額を出せない制度）
//   }
//   補助率の基本値（RATE_BASE）は calc から自動で出す（いちばん低い率＝安全側）ので書かない。
//
